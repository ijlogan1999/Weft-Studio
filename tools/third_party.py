#!/usr/bin/env python3
"""Third-party license manifest for Weft Studio (F-SYS-1, AT-SYS-1).

Sources of truth:
  * third_party/cpp-deps.json - every C++ dependency. CMake fetches C++
    dependencies only from this file, so nothing can be linked without an entry.
  * Cargo.lock / `cargo metadata` - every Rust crate linked into a shipped
    binary (weft-crdt is linked into the app, weft-relay is the server).

Commands:
  --write              regenerate THIRD_PARTY.md
  --check              fail if THIRD_PARTY.md is stale or any dependency lacks a
                       license expression or license text
  --notices OUT        write the full notices text (embedded in the app's About box)
  --cpp-src NAME=DIR   source dir of a fetched C++ dependency, so its license files
                       can be verified and included (repeatable)
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CPP_DEPS = ROOT / "third_party" / "cpp-deps.json"
SPDX_DIR = ROOT / "third_party" / "licenses"
OUTPUT_MD = ROOT / "THIRD_PARTY.md"

# Rust packages in this workspace whose dependency trees ship, and where.
SHIPPED_RUST_ROOTS = {"weft-crdt": "app", "weft-relay": "relay"}
LICENSE_FILE_RE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.IGNORECASE)


def spdx_ids(expr: str) -> list[str]:
    tokens = re.split(r"[\s()/]+", expr.replace(" OR ", " ").replace(" AND ", " ").replace(" WITH ", " "))
    return sorted({t for t in tokens if t and t not in {"OR", "AND", "WITH"}})


def cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def rust_packages(meta: dict) -> dict[str, dict]:
    """Returns {package id: {pkg, used_by: set}} for normal (non-dev, non-build) deps."""
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    found: dict[str, dict] = {}
    for root_id in workspace:
        where = SHIPPED_RUST_ROOTS.get(pkgs[root_id]["name"])
        if where is None:
            continue
        stack = [root_id]
        seen = set()
        while stack:
            cur = stack.pop()
            if cur in seen:
                continue
            seen.add(cur)
            for dep in nodes[cur]["deps"]:
                if not any(k["kind"] is None for k in dep["dep_kinds"]):
                    continue
                if dep["pkg"] not in workspace:
                    entry = found.setdefault(dep["pkg"], {"pkg": pkgs[dep["pkg"]], "used_by": set()})
                    entry["used_by"].add(where)
                stack.append(dep["pkg"])
    return found


def crate_license_files(pkg: dict) -> list[Path]:
    crate_dir = Path(pkg["manifest_path"]).parent
    files = sorted(p for p in crate_dir.iterdir() if p.is_file() and LICENSE_FILE_RE.match(p.name))
    if pkg.get("license_file"):
        extra = crate_dir / pkg["license_file"]
        if extra.is_file() and extra not in files:
            files.append(extra)
    return files


def load_cpp_deps() -> dict:
    return json.loads(CPP_DEPS.read_text(encoding="utf-8"))


def render_markdown(cpp: dict, rust: dict[str, dict]) -> str:
    lines = [
        "# Third-party components",
        "",
        "Weft Studio is licensed under the GNU Affero General Public License v3 (see `LICENSE`).",
        "This file lists every third-party component it is built with. It is generated by",
        "`tools/third_party.py --write`; CI fails if it is stale (AT-SYS-1). The app's About box",
        "shows the full license texts.",
        "",
        "Bundled content (sounds, icons, fonts, demo projects): none yet. Every bundled asset must be",
        "original or redistributable and be listed here.",
        "",
        "## C++ libraries",
        "",
        "| Component | Version | License | Ships | Purpose |",
        "|---|---|---|---|---|",
    ]
    for name, dep in sorted(cpp.items()):
        ships = "yes" if dep["ships"] else "no (build/test only)"
        lines.append(f"| {name} | {dep['tag']} | {dep['license']} | {ships} | {dep['purpose']} |")
        for b in dep.get("bundled", []):
            note = f" {b['note']}" if b.get("note") else ""
            lines.append(f"| ↳ {b['name']} (inside {name}) | | {b['license']} | {ships} |{note} |")
    for where, title in (("app", "Rust crates linked into the app (via weft-crdt)"), ("relay", "Rust crates in the relay server")):
        lines += ["", f"## {title}", "", "| Crate | Version | License |", "|---|---|---|"]
        for entry in sorted(rust.values(), key=lambda e: (e["pkg"]["name"], e["pkg"]["version"])):
            if where in entry["used_by"]:
                p = entry["pkg"]
                lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'UNKNOWN'} |")
    return "\n".join(lines) + "\n"


def check(cpp: dict, rust: dict[str, dict], cpp_src: dict[str, Path]) -> list[str]:
    errors = []
    for entry in rust.values():
        p = entry["pkg"]
        if not p.get("license"):
            errors.append(f"crate {p['name']} {p['version']} has no license expression")
            continue
        if not crate_license_files(p):
            missing = [i for i in spdx_ids(p["license"]) if not (SPDX_DIR / f"{i}.txt").exists()]
            if missing:
                errors.append(f"crate {p['name']} {p['version']} ships no license file and "
                              f"third_party/licenses lacks {', '.join(missing)}")
    for name, src in cpp_src.items():
        dep = cpp.get(name)
        if dep is None:
            errors.append(f"C++ dependency {name} is fetched but missing from cpp-deps.json")
            continue
        files = list(dep["license_files"]) + [f for b in dep.get("bundled", []) for f in b["license_files"]]
        for f in files:
            if not (src / f).is_file():
                errors.append(f"{name}: license file {f} not found in {src}")
    return errors


def render_notices(cpp: dict, rust: dict[str, dict], cpp_src: dict[str, Path]) -> str:
    parts = ["Weft Studio third-party notices\n"]

    def section(title: str, texts: list[str]) -> None:
        parts.append("=" * 78 + f"\n{title}\n" + "=" * 78 + "\n")
        parts.extend(t.rstrip() + "\n\n" for t in texts)

    for name, dep in sorted(cpp.items()):
        if not dep["ships"]:
            continue
        src = cpp_src.get(name)
        items = [(name, dep)] + [(b["name"], b) for b in dep.get("bundled", [])]
        for title, d in items:
            texts = [(src / f).read_text(encoding="utf-8", errors="replace") for f in d["license_files"]] if src else []
            section(f"{title} ({d['license']})", texts or [f"License: {d['license']}"])
    for entry in sorted(rust.values(), key=lambda e: e["pkg"]["name"]):
        if "app" not in entry["used_by"]:
            continue
        p = entry["pkg"]
        files = crate_license_files(p)
        texts = [f.read_text(encoding="utf-8", errors="replace") for f in files]
        if not texts:
            texts = [(SPDX_DIR / f"{i}.txt").read_text(encoding="utf-8") for i in spdx_ids(p["license"])
                     if (SPDX_DIR / f"{i}.txt").exists()]
        section(f"{p['name']} {p['version']} ({p['license']})", texts)
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--notices", type=Path)
    ap.add_argument("--cpp-src", action="append", default=[], metavar="NAME=DIR")
    args = ap.parse_args()

    cpp = load_cpp_deps()
    cpp_src = {}
    for item in args.cpp_src:
        name, _, path = item.partition("=")
        cpp_src[name] = Path(path)
    rust = rust_packages(cargo_metadata())
    md = render_markdown(cpp, rust)

    status = 0
    if args.write:
        OUTPUT_MD.write_text(md, encoding="utf-8", newline="\n")
    if args.check:
        errors = check(cpp, rust, cpp_src)
        current = OUTPUT_MD.read_text(encoding="utf-8") if OUTPUT_MD.exists() else ""
        if current.replace("\r\n", "\n") != md:
            errors.append("THIRD_PARTY.md is stale: run `python tools/third_party.py --write`")
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        status = 1 if errors else 0
        if not errors:
            print(f"third-party manifest OK: {len(cpp)} C++ deps, {len(rust)} Rust crates")
    if args.notices:
        args.notices.parent.mkdir(parents=True, exist_ok=True)
        args.notices.write_text(render_notices(cpp, rust, cpp_src), encoding="utf-8", newline="\n")
    return status


if __name__ == "__main__":
    sys.exit(main())
